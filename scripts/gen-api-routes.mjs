// Generates app/server/routes.gen.ts: one entry per app/endpoints/<route>_<METHOD>.ts file.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../app/endpoints/", import.meta.url).pathname;
const files = [];
(function walk(dir) {
  for (const f of readdirSync(dir).sort()) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/_(GET|POST)\.ts$/.test(f) && !f.endsWith(".schema.ts")) files.push(relative(root, p));
  }
})(root);

const lines = files.map((f, i) => {
  const m = /^(.*)_(GET|POST)\.ts$/.exec(f);
  return { imp: `import * as r${i} from "../endpoints/${f.replace(/\.ts$/, "")}";`, entry: `  "${m[2]} ${m[1]}": r${i},` };
});
writeFileSync(
  new URL("../app/server/routes.gen.ts", import.meta.url),
  `// Generated by scripts/gen-api-routes.mjs. Do not edit.\n${lines.map((l) => l.imp).join("\n")}\n\nexport const routes: Record<string, { handle: (request: Request) => Promise<Response> | Response }> = {\n${lines.map((l) => l.entry).join("\n")}\n};\n`,
);
console.log(`routes.gen.ts: ${files.length} endpoints`);
